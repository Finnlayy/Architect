import React, { useState } from 'react';
import {
  Shield,
  CheckCircle2,
  AlertTriangle,
  XCircle,
  Sliders,
  Maximize2,
  ArrowRight,
  Sparkles,
  Info,
  TrendingDown,
  Activity,
  Layers,
  Zap,
} from 'lucide-react';
import { JudgeVerdict, JudgeConfig, PortfolioState } from '../types/trading';

interface JudgeGateViewProps {
  verdicts: JudgeVerdict[];
  config: JudgeConfig;
  onUpdateConfig: (newConfig: JudgeConfig) => void;
  portfolio: PortfolioState;
  onInjectTestSignal: (type: 'NORMAL' | 'OVERSIZED' | 'LATENCY_STALE' | 'WIDE_SPREAD') => void;
}

export const JudgeGateView: React.FC<JudgeGateViewProps> = ({
  verdicts,
  config,
  onUpdateConfig,
  portfolio,
  onInjectTestSignal,
}) => {
  const [selectedVerdict, setSelectedVerdict] = useState<JudgeVerdict | null>(
    verdicts[0] || null
  );
  const [statusFilter, setStatusFilter] = useState<'ALL' | 'PASSED' | 'MODIFIED' | 'REJECTED'>('ALL');
  const [isEditingConfig, setIsEditingConfig] = useState(false);
  const [draftConfig, setDraftConfig] = useState<JudgeConfig>(config);

  const filteredVerdicts = verdicts.filter((v) => {
    if (statusFilter === 'ALL') return true;
    return v.status === statusFilter;
  });

  const handleSaveConfig = () => {
    onUpdateConfig(draftConfig);
    setIsEditingConfig(false);
  };

  const gateMeta = [
    { id: 'M1', name: 'Sanity & Latency', desc: 'Tick timestamp freshness ≤ 500ms, non-empty payload', type: 'HARD_REJECT' },
    { id: 'M2', name: 'Gross & Net Barrier', desc: `Leverage ≤ ${config.maxGrossLeverage}x, Conc ≤ ${config.maxAssetConcentrationPct}%`, type: 'HARD_REJECT' },
    { id: 'M3', name: 'Volatility Filter', desc: 'GARCH/Parkinson ratio ≤ 2.5x with proportional dampening', type: 'SCALE_FACTOR' },
    { id: 'M4', name: 'Kelly Sizer', desc: `Half-Kelly allocation (c=${config.kellyFraction}) & confidence scaling`, type: 'MODIFIER' },
    { id: 'M5', name: 'Drawdown Breaker', desc: `Daily loss ≤ ${config.maxDailyDrawdownPct}%, Peak DD ≤ ${config.maxTotalDrawdownPct}%`, type: 'CIRCUIT_BREAKER' },
    { id: 'M6', name: 'ADV & Spread', desc: `Max spread ≤ ${config.maxSpreadBpsThreshold} bps, ≤1.5% rolling volume`, type: 'SLIPPAGE_BARRIER' },
    { id: 'M7', name: '99% CVaR Tail Shock', desc: `Projected Expected Shortfall ≤ $${config.cvarLimitUsd.toLocaleString()}`, type: 'RISK_CAP' },
    { id: 'M8', name: 'Execution Routing', desc: 'Optimal TWAP/VWAP/DMA/Iceberg slicing protocol', type: 'ROUTER' },
  ];

  return (
    <div className="space-y-4">
      {/* Top Overview: Philosophy & Gate Matrix Architecture */}
      <div className="bg-slate-900 border border-slate-800 rounded-lg p-4">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 border-b border-slate-800 pb-3">
          <div>
            <div className="flex items-center gap-2">
              <Shield className="w-5 h-5 text-amber-400" />
              <h2 className="text-base font-bold text-slate-100 font-mono tracking-tight">
                THE JUDGE &amp; M8-GATE RISK INVARIANTS
              </h2>
            </div>
            <p className="text-xs text-slate-400 mt-1 max-w-3xl">
              Signals generated by The Swarm possess zero execution autonomy. Every speculative thesis must pass through all 8 sequential risk barriers before any capital is allocated.
            </p>
          </div>

          {/* Quant Stress Test Injections */}
          <div className="flex items-center gap-2 flex-wrap">
            <span className="text-[11px] font-mono text-slate-400">INJECT TEST:</span>
            <button
              onClick={() => onInjectTestSignal('NORMAL')}
              className="px-2.5 py-1 text-[11px] font-mono bg-emerald-500/10 text-emerald-400 border border-emerald-500/30 rounded hover:bg-emerald-500/20 transition-colors"
            >
              + Alpha Sig
            </button>
            <button
              onClick={() => onInjectTestSignal('OVERSIZED')}
              className="px-2.5 py-1 text-[11px] font-mono bg-amber-500/10 text-amber-400 border border-amber-500/30 rounded hover:bg-amber-500/20 transition-colors"
            >
              + Oversized
            </button>
            <button
              onClick={() => onInjectTestSignal('LATENCY_STALE')}
              className="px-2.5 py-1 text-[11px] font-mono bg-rose-500/10 text-rose-400 border border-rose-500/30 rounded hover:bg-rose-500/20 transition-colors"
            >
              + Stale Latency
            </button>
            <button
              onClick={() => onInjectTestSignal('WIDE_SPREAD')}
              className="px-2.5 py-1 text-[11px] font-mono bg-purple-500/10 text-purple-400 border border-purple-500/30 rounded hover:bg-purple-500/20 transition-colors"
            >
              + Illiquid Spread
            </button>
          </div>
        </div>

        {/* 8 Gates Pipeline Visual Grid */}
        <div className="grid grid-cols-2 sm:grid-cols-4 lg:grid-cols-8 gap-2 mt-4">
          {gateMeta.map((gate, idx) => (
            <div
              key={gate.id}
              className="bg-slate-950 p-2.5 rounded border border-slate-800 flex flex-col justify-between hover:border-slate-700 transition-colors"
            >
              <div className="flex items-center justify-between mb-1">
                <span className="font-mono font-bold text-xs text-amber-400">{gate.id}</span>
                <span className="text-[9px] px-1 py-0.5 rounded font-mono bg-slate-800 text-slate-300">
                  #{idx + 1}
                </span>
              </div>
              <p className="text-[11px] font-semibold text-slate-200 line-clamp-1">{gate.name}</p>
              <p className="text-[10px] text-slate-400 mt-1 line-clamp-2 leading-tight">{gate.desc}</p>
              <div className="mt-2 pt-1 border-t border-slate-800/80 flex items-center justify-between text-[9px] font-mono text-slate-500">
                <span>{gate.type}</span>
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* Main Two-Column Layout: Live Verdict Stream vs Selected Verdict Deep Dive */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-4">
        {/* Left Column: Verdict Stream & Filters (7 cols) */}
        <div className="lg:col-span-7 bg-slate-900 border border-slate-800 rounded-lg p-4 flex flex-col">
          <div className="flex items-center justify-between mb-3">
            <div className="flex items-center gap-2">
              <Activity className="w-4 h-4 text-emerald-400" />
              <h3 className="text-xs font-bold font-mono text-slate-200 uppercase tracking-wider">
                Adjudication Stream ({filteredVerdicts.length})
              </h3>
            </div>

            {/* Filter Pills */}
            <div className="flex items-center gap-1">
              {(['ALL', 'PASSED', 'MODIFIED', 'REJECTED'] as const).map((filter) => (
                <button
                  key={filter}
                  onClick={() => setStatusFilter(filter)}
                  className={`px-2 py-0.5 text-[10px] font-mono rounded transition-colors ${
                    statusFilter === filter
                      ? 'bg-slate-700 text-slate-100 font-semibold'
                      : 'text-slate-400 hover:bg-slate-800'
                  }`}
                >
                  {filter}
                </button>
              ))}
            </div>
          </div>

          {/* Verdicts List */}
          <div className="space-y-2 max-h-[520px] overflow-y-auto pr-1">
            {filteredVerdicts.length === 0 ? (
              <div className="p-8 text-center text-slate-500 font-mono text-xs">
                Waiting for incoming Swarm signals to adjudicate...
              </div>
            ) : (
              filteredVerdicts.map((v) => {
                const isSelected = selectedVerdict?.signalId === v.signalId;
                const statusColor =
                  v.status === 'PASSED'
                    ? 'border-emerald-500/40 bg-emerald-500/5 hover:border-emerald-500/60'
                    : v.status === 'MODIFIED'
                    ? 'border-amber-500/40 bg-amber-500/5 hover:border-amber-500/60'
                    : 'border-rose-500/40 bg-rose-500/5 hover:border-rose-500/60';

                return (
                  <div
                    key={`${v.signalId}-${v.timestamp}`}
                    onClick={() => setSelectedVerdict(v)}
                    className={`p-2.5 rounded border transition-all cursor-pointer ${
                      isSelected ? 'ring-1 ring-amber-400/80 bg-slate-800/90' : 'bg-slate-950/70'
                    } ${statusColor}`}
                  >
                    <div className="flex items-center justify-between text-xs mb-1">
                      <div className="flex items-center gap-2">
                        <span className="font-mono font-bold text-slate-200">{v.symbol}</span>
                        <span
                          className={`font-mono text-[10px] px-1.5 py-0.2 rounded ${
                            v.direction === 'LONG'
                              ? 'bg-emerald-500/20 text-emerald-300 font-bold'
                              : 'bg-rose-500/20 text-rose-300 font-bold'
                          }`}
                        >
                          {v.direction}
                        </span>
                        <span className="text-[11px] text-slate-400 font-mono">{v.signalId}</span>
                      </div>

                      <div className="flex items-center gap-2">
                        <span
                          className={`text-[10px] px-2 py-0.5 rounded font-mono font-bold flex items-center gap-1 ${
                            v.status === 'PASSED'
                              ? 'bg-emerald-500/20 text-emerald-400'
                              : v.status === 'MODIFIED'
                              ? 'bg-amber-500/20 text-amber-400'
                              : 'bg-rose-500/20 text-rose-400'
                          }`}
                        >
                          {v.status === 'PASSED' && <CheckCircle2 className="w-3 h-3" />}
                          {v.status === 'MODIFIED' && <AlertTriangle className="w-3 h-3" />}
                          {v.status === 'REJECTED' && <XCircle className="w-3 h-3" />}
                          {v.status}
                        </span>
                        <span className="text-[10px] font-mono text-slate-500">
                          {new Date(v.timestamp).toLocaleTimeString()}
                        </span>
                      </div>
                    </div>

                    <div className="flex items-center justify-between text-[11px] font-mono text-slate-300 mt-1.5 pt-1 border-t border-slate-800/60">
                      <div>
                        <span className="text-slate-500">Alloc: </span>
                        <span className="font-semibold text-slate-200">
                          ${v.approvedSizeUsd.toLocaleString()}
                        </span>
                        {v.approvedSizeUsd !== v.originalSizeUsd && (
                          <span className="text-slate-500 line-through ml-1.5 text-[10px]">
                            ${v.originalSizeUsd.toLocaleString()}
                          </span>
                        )}
                        {v.scaleFactor < 1 && v.scaleFactor > 0 && (
                          <span className="text-amber-400 text-[10px] ml-1">
                            ({Math.round(v.scaleFactor * 100)}%)
                          </span>
                        )}
                      </div>

                      <div className="flex items-center gap-2">
                        <span className="text-slate-500">Route:</span>
                        <span className="text-blue-400 text-[10px] font-semibold">
                          {v.executionRoute}
                        </span>
                        {v.failedGate && (
                          <span className="text-rose-400 text-[10px] bg-rose-500/10 px-1 rounded">
                            Violated {v.failedGate}
                          </span>
                        )}
                      </div>
                    </div>
                  </div>
                );
              })
            )}
          </div>
        </div>

        {/* Right Column: Selected Verdict Inspector & Parameter Tuner (5 cols) */}
        <div className="lg:col-span-5 space-y-4">
          {/* Selected Verdict Deep-Dive */}
          <div className="bg-slate-900 border border-slate-800 rounded-lg p-4">
            <div className="flex items-center justify-between border-b border-slate-800 pb-2 mb-3">
              <div className="flex items-center gap-1.5">
                <Layers className="w-4 h-4 text-amber-400" />
                <h3 className="text-xs font-bold font-mono text-slate-200 uppercase tracking-wider">
                  M-Gate Audit Trail
                </h3>
              </div>
              {selectedVerdict && (
                <span className="text-[10px] font-mono text-slate-400">
                  {selectedVerdict.signalId}
                </span>
              )}
            </div>

            {selectedVerdict ? (
              <div className="space-y-3">
                {/* Summary Card */}
                <div className="bg-slate-950 p-3 rounded border border-slate-800 text-xs font-mono">
                  <div className="flex justify-between items-center mb-2">
                    <span className="text-slate-400">Verdict:</span>
                    <span
                      className={`font-bold px-2 py-0.5 rounded text-[11px] ${
                        selectedVerdict.status === 'PASSED'
                          ? 'bg-emerald-500/20 text-emerald-400'
                          : selectedVerdict.status === 'MODIFIED'
                          ? 'bg-amber-500/20 text-amber-400'
                          : 'bg-rose-500/20 text-rose-400'
                      }`}
                    >
                      {selectedVerdict.status}
                    </span>
                  </div>
                  <div className="grid grid-cols-2 gap-2 text-[11px] pt-2 border-t border-slate-800/80">
                    <div>
                      <span className="text-slate-500 block">Requested Capital</span>
                      <span className="text-slate-200 font-bold">
                        ${selectedVerdict.originalSizeUsd.toLocaleString()}
                      </span>
                    </div>
                    <div>
                      <span className="text-slate-500 block">Approved Allocation</span>
                      <span className="text-emerald-400 font-bold">
                        ${selectedVerdict.approvedSizeUsd.toLocaleString()}
                      </span>
                    </div>
                    <div>
                      <span className="text-slate-500 block">Execution Protocol</span>
                      <span className="text-blue-400 font-bold">{selectedVerdict.executionRoute}</span>
                    </div>
                    <div>
                      <span className="text-slate-500 block">Slices / Urgency</span>
                      <span className="text-slate-200">
                        {selectedVerdict.executionParams.sliceCount} slices ({selectedVerdict.executionParams.urgency})
                      </span>
                    </div>
                  </div>
                </div>

                {/* Gate Evaluation List */}
                <div className="space-y-2 max-h-[320px] overflow-y-auto pr-1">
                  {selectedVerdict.gateResults.map((gate) => (
                    <div
                      key={gate.gateId}
                      className={`p-2 rounded border text-xs font-mono ${
                        gate.passed
                          ? 'bg-slate-950/60 border-slate-800 text-slate-300'
                          : 'bg-rose-950/20 border-rose-800/50 text-rose-200'
                      }`}
                    >
                      <div className="flex items-center justify-between mb-1">
                        <div className="flex items-center gap-1.5 font-bold">
                          {gate.passed ? (
                            <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
                          ) : (
                            <XCircle className="w-3.5 h-3.5 text-rose-400" />
                          )}
                          <span className="text-amber-400">{gate.gateId}</span>
                          <span className="text-slate-200 text-[11px]">{gate.name}</span>
                        </div>
                        <span
                          className={`text-[9px] px-1.5 py-0.2 rounded uppercase ${
                            gate.passed ? 'text-emerald-400 bg-emerald-500/10' : 'text-rose-400 bg-rose-500/10'
                          }`}
                        >
                          {gate.passed ? 'PASS' : 'FAIL'}
                        </span>
                      </div>
                      <p className="text-[10px] text-slate-400 leading-relaxed pl-5">
                        {gate.reason}
                      </p>
                    </div>
                  ))}
                </div>
              </div>
            ) : (
              <div className="p-8 text-center text-slate-500 font-mono text-xs">
                Select a verdict from the stream to inspect gate evaluations
              </div>
            )}
          </div>

          {/* Risk Invariants Parameter Tuner */}
          <div className="bg-slate-900 border border-slate-800 rounded-lg p-4">
            <div className="flex items-center justify-between border-b border-slate-800 pb-2 mb-3">
              <div className="flex items-center gap-1.5">
                <Sliders className="w-4 h-4 text-emerald-400" />
                <h3 className="text-xs font-bold font-mono text-slate-200 uppercase tracking-wider">
                  Risk Parameter Constraints
                </h3>
              </div>
              <button
                onClick={() => {
                  if (isEditingConfig) handleSaveConfig();
                  else setIsEditingConfig(true);
                }}
                className="text-[11px] font-mono px-2 py-0.5 rounded bg-slate-800 text-slate-200 hover:bg-slate-700 transition-colors border border-slate-700"
              >
                {isEditingConfig ? 'Save Parameters' : 'Edit Thresholds'}
              </button>
            </div>

            <div className="space-y-3 text-xs font-mono">
              <div className="flex items-center justify-between">
                <span className="text-slate-400">Max Gross Leverage:</span>
                {isEditingConfig ? (
                  <input
                    type="number"
                    step="0.1"
                    min="1.0"
                    max="5.0"
                    value={draftConfig.maxGrossLeverage}
                    onChange={(e) =>
                      setDraftConfig({ ...draftConfig, maxGrossLeverage: parseFloat(e.target.value) || 3.0 })
                    }
                    className="w-20 bg-slate-950 border border-slate-700 px-1.5 py-0.5 rounded text-right text-slate-100"
                  />
                ) : (
                  <span className="text-slate-200 font-bold">{config.maxGrossLeverage}x NAV</span>
                )}
              </div>

              <div className="flex items-center justify-between">
                <span className="text-slate-400">Max Asset Concentration:</span>
                {isEditingConfig ? (
                  <input
                    type="number"
                    step="1"
                    min="5"
                    max="50"
                    value={draftConfig.maxAssetConcentrationPct}
                    onChange={(e) =>
                      setDraftConfig({
                        ...draftConfig,
                        maxAssetConcentrationPct: parseFloat(e.target.value) || 20,
                      })
                    }
                    className="w-20 bg-slate-950 border border-slate-700 px-1.5 py-0.5 rounded text-right text-slate-100"
                  />
                ) : (
                  <span className="text-slate-200 font-bold">{config.maxAssetConcentrationPct}%</span>
                )}
              </div>

              <div className="flex items-center justify-between">
                <span className="text-slate-400">Kelly Fraction (Damping):</span>
                {isEditingConfig ? (
                  <input
                    type="number"
                    step="0.05"
                    min="0.1"
                    max="1.0"
                    value={draftConfig.kellyFraction}
                    onChange={(e) =>
                      setDraftConfig({ ...draftConfig, kellyFraction: parseFloat(e.target.value) || 0.5 })
                    }
                    className="w-20 bg-slate-950 border border-slate-700 px-1.5 py-0.5 rounded text-right text-slate-100"
                  />
                ) : (
                  <span className="text-slate-200 font-bold">{config.kellyFraction} (Half-Kelly)</span>
                )}
              </div>

              <div className="flex items-center justify-between">
                <span className="text-slate-400">Daily Drawdown Limit:</span>
                {isEditingConfig ? (
                  <input
                    type="number"
                    step="0.5"
                    min="1.0"
                    max="10.0"
                    value={draftConfig.maxDailyDrawdownPct}
                    onChange={(e) =>
                      setDraftConfig({
                        ...draftConfig,
                        maxDailyDrawdownPct: parseFloat(e.target.value) || 2.5,
                      })
                    }
                    className="w-20 bg-slate-950 border border-slate-700 px-1.5 py-0.5 rounded text-right text-slate-100"
                  />
                ) : (
                  <span className="text-rose-400 font-bold">-{config.maxDailyDrawdownPct}%</span>
                )}
              </div>

              <div className="flex items-center justify-between">
                <span className="text-slate-400">Max 99% CVaR Budget:</span>
                {isEditingConfig ? (
                  <input
                    type="number"
                    step="1000"
                    min="5000"
                    max="100000"
                    value={draftConfig.cvarLimitUsd}
                    onChange={(e) =>
                      setDraftConfig({ ...draftConfig, cvarLimitUsd: parseFloat(e.target.value) || 25000 })
                    }
                    className="w-24 bg-slate-950 border border-slate-700 px-1.5 py-0.5 rounded text-right text-slate-100"
                  />
                ) : (
                  <span className="text-amber-400 font-bold">${config.cvarLimitUsd.toLocaleString()}</span>
                )}
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
